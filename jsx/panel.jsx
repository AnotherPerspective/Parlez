// Parlez! - the switch inside After Effects.
//
// A ScriptUI panel: plain ExtendScript, no CEP, no extension. `install-panel`
// copies this file into the user-level Scripts/ScriptUI Panels folder as
// "Parlez!.jsx", and After Effects lists it under the Window menu by that
// name; it docks like any other panel. Run as an ordinary script (File >
// Scripts > Run Script File...) it opens as a floating window instead.
//
// What it shows:
//   - one big ON / OFF button inside a coloured frame, which is also the
//     traffic light: green = Claude may work and is waiting, yellow =
//     requests are waiting or one is running, red = OFF, stopped, grey =
//     the resident agent is not there or not answering. One click on the
//     button switches Claude on or off;
//   - "Sola lettura": Claude may look at the project but not change it;
//   - the last requests, in plain Italian, with outcome and duration;
//   - quick buttons: undo Claude's last change, restore point now, restore
//     points folder, history file, mailbox, the layout switch;
//   - small at the bottom: counters, instance id, agent version.
// Two layouts, "verticale" for a side column and "compatta" (horizontal) to
// dock under the timeline; "Vista" saves the choice for the next opening.
//
// STABILITY FIRST. Custom painting in docked ScriptUI panels is fragile, and
// mouse events on groups and statictexts never reach a script in After
// Effects (AE 26.5, 2026-10-27). So: no onDraw, no custom painting, no
// update(), no mouse listeners. The ON/OFF block is an `iconbutton` in
// "toolbutton" style - After Effects delivers its clicks reliably and draws
// no frame or focus outline around it - showing a picture of the block, one
// per state, with lighter and darker versions for mouse-over and pressed
// handed to ScriptUI.newImage. The pictures live in the package
// (jsx/panel-images/, generated by src/panel-images.ts); install-panel writes
// their folder into IMAGE_DIR below. Without them the block falls back to a
// plain button reading ON / OFF. Controls are created once, when the panel
// opens, and never removed or rebuilt while it is open. The timer refresh
// only changes texts and pictures, only when they changed, does nothing
// while the panel is hidden, and lays the panel out again only when the
// history goes from empty to not empty. Nothing outside the panel (the
// agent included) calls into it.
//
// How it talks to the rest. The switches are app.settings entries in the
// "Parlez" section (claudeEnabled, readOnly; layout is the
// panel's own). Whether Claude may work is decided by ONE function,
// AE_MCP.isEnabled in jsx/serve.jsx, which the agent loads and exports on
// $.global: the panel calls it, and only when it is missing (no agent in this
// After Effects) uses its own copy of the same rule - only "1" means on.
// Everything else comes from the agent: $.global.AE_MCP_AGENT or, failing
// that, the heartbeat file it writes.
//
// Self-contained on purpose: the file is copied, not loaded from the
// package, so it cannot #include anything. Section, keys and the restore
// point folder and naming are mirrored in src/config.ts and
// src/operations/checkpoint.ts (tests keep them in step).
//
// Keep this file ES3: var only, no arrow functions, no Array.prototype.map.
// Strings shown to the user use \u escapes for accented letters, so the file
// reads the same whatever encoding After Effects assumes for it.

(function aeMcpPanel(thisObj) {
    var SECTION = "Parlez";
    var KEY_ENABLED = "claudeEnabled";
    var KEY_READ_ONLY = "readOnly";
    var KEY_LAYOUT = "layout";
    var TITLE = "Parlez!";
    // Never under a second (see STABILITY FIRST above).
    var REFRESH_MS = 1500;
    // The agent refreshes its heartbeat every second; the server presumes it
    // gone after five (HEARTBEAT_STALE_MS in src/config.ts).
    var STALE_MS = 5000;
    // First agent versions that know each switch (jsx/agent.jsx AGENT_VERSION).
    var PAUSE_AGENT_VERSION = 2;
    var READ_ONLY_AGENT_VERSION = 3;
    // Same folder and naming as checkpoint.create (src/operations/checkpoint.ts).
    var CHECKPOINT_SUBDIR = "_parlez-checkpoints";
    var CHECKPOINT_LABEL = "pannello";
    var CHECKPOINT_MAX_COPY = 999;
    // Edit > Undo.
    var UNDO_COMMAND = 16;
    var TITLE_CHARS = 30;
    // The signature at the bottom right opens this page in the user's own
    // browser when clicked (nome provvisorio dell'indirizzo, da confermare con
    // Anthony). That is the user opening a page, not this program going on
    // the internet: nothing here connects anywhere, the click hands the
    // address to the operating system, as a link in any document would.
    var SITE_URL = "https://www.anotherperspectivepictures.com";
    // Written by install-panel: the package's jsx/panel-images folder.
    var IMAGE_DIR = null; // INSTALL_PANEL_IMAGE_DIR

    var GREEN = [0.20, 0.72, 0.36];
    var RED = [0.86, 0.24, 0.20];
    var YELLOW = [0.95, 0.72, 0.12];
    var GREY = [0.42, 0.42, 0.42];
    var BG = [0.18, 0.18, 0.18];
    var SECTION_BG = [0.21, 0.21, 0.21];
    var TEXT = [0.86, 0.86, 0.86];
    var DIM = [0.55, 0.55, 0.55];

    // --- Switches -------------------------------------------------------
    function readSwitch(key) {
        try {
            if (!app.settings.haveSetting(SECTION, key)) return null;
            return String(app.settings.getSetting(SECTION, key));
        } catch (eRead) {
            return null;
        }
    }

    /** Save, then read back: true only when After Effects kept the value. */
    function writeSwitch(key, value) {
        try {
            app.settings.saveSetting(SECTION, key, value);
        } catch (eWrite) { /* told by the read-back */ }
        return readSwitch(key) === value;
    }

    /** The one rule (AE_MCP.isEnabled, jsx/serve.jsx); its copy when there is no agent. */
    function readEnabled() {
        try {
            var shared = $.global.AE_MCP;
            if (shared && typeof shared.isEnabled === "function") return shared.isEnabled() === true;
        } catch (eShared) { /* fall back to the copy */ }
        return readSwitch(KEY_ENABLED) === "1";
    }

    function readReadOnly() {
        return readSwitch(KEY_READ_ONLY) === "1";
    }

    function readLayout() {
        return (readSwitch(KEY_LAYOUT) === "compatta") ? "compatta" : "verticale";
    }

    // --- What the agent says --------------------------------------------
    function numberOr(value, fallback) {
        return (typeof value === "number") ? value : fallback;
    }

    function readHeartbeat(dir) {
        try {
            if (typeof JSON === "undefined" || typeof JSON.parse !== "function") return null;
            var f = new File(dir + "/heartbeat.json");
            if (!f.exists) return null;
            f.encoding = "UTF-8";
            if (!f.open("r")) return null;
            var raw = f.read();
            f.close();
            return JSON.parse(raw);
        } catch (eHb) {
            return null;
        }
    }

    /** Everything the panel shows about the agent, or null when there is none. */
    function readAgent() {
        var state = null;
        try {
            var agent = $.global.AE_MCP_AGENT;
            if (agent && agent.state) state = agent.state;
        } catch (eAgent) { /* no agent in this engine */ }
        if (state === null) return null;
        var dir = (typeof state.dir === "string") ? state.dir : null;
        var hb = (dir !== null) ? readHeartbeat(dir) : null;
        // Live memory first (same engine); the heartbeat file when a field
        // is missing there.
        function pick(name, fallback) {
            if (state[name] !== undefined && state[name] !== null) return state[name];
            if (hb !== null && hb[name] !== undefined && hb[name] !== null) return hb[name];
            return fallback;
        }
        var recent = pick("recent", []);
        return {
            id: String(state.id),
            version: numberOr(state.agentVersion, 1),
            dir: dir,
            served: numberOr(pick("served", 0), 0),
            refused: numberOr(pick("refused", 0), 0),
            busy: pick("busy", false) === true,
            pending: numberOr(pick("pending", 0), 0),
            lastRequestAt: numberOr(pick("lastRequestAt", null), 0),
            recent: (recent && typeof recent.length === "number") ? recent : [],
            historyPath: (typeof state.historyPath === "string") ? state.historyPath : null,
            // While a request runs the heartbeat is not refreshed, and that is fine.
            heartbeatAt: state.busy ? new Date().getTime() : numberOr(hb !== null ? hb.ts : state.lastHeartbeatAt, 0)
        };
    }

    // --- What to show ---------------------------------------------------
    function pad2(n) {
        return (n < 10 ? "0" : "") + String(n);
    }

    function clock(ms) {
        var d = new Date(ms);
        return pad2(d.getHours()) + ":" + pad2(d.getMinutes()) + ":" + pad2(d.getSeconds());
    }

    function seconds(ms) {
        if (typeof ms !== "number" || ms < 0) return "";
        if (ms < 10000) return (Math.round(ms / 100) / 10).toString().replace(".", ",") + " s";
        return String(Math.round(ms / 1000)) + " s";
    }

    function shorten(value, max) {
        var s = String(value);
        return (s.length > max) ? s.substring(0, max - 1) + "\u2026" : s;
    }

    /**
     * The block: { label, color, status, tip }. The switch decides first;
     * then whether the agent can be reached; then what it is doing.
     */
    function blockFor(enabled, readOnly, agent, now) {
        var ro = readOnly ? " \u00b7 sola lettura" : "";
        if (enabled !== true) {
            return { label: "OFF", look: "off", color: RED, status: "Claude fermo",
                tip: "Claude non pu\u00f2 toccare After Effects: ogni sua richiesta viene rifiutata." };
        }
        if (agent === null) {
            return { label: "ON", look: "idle", color: GREY, status: "non collegato",
                tip: "Lo script di avvio non \u00e8 attivo in questo After Effects: Claude non riesce a collegarsi. " +
                    "Installalo (install-agent) e riavvia After Effects." };
        }
        if (agent.version < PAUSE_AGENT_VERSION) {
            return { label: "ON", look: "idle", color: GREY, status: "riavvia After Effects",
                tip: "Lo script di avvio caricato \u00e8 una versione vecchia che non conosce l'interruttore." };
        }
        if (agent.heartbeatAt === 0 || now - agent.heartbeatAt > STALE_MS) {
            return { label: "ON", look: "idle", color: GREY, status: "non risponde",
                tip: "Lo script di avvio \u00e8 caricato ma il battito non si aggiorna: una finestra di dialogo aperta?" };
        }
        if (agent.busy) {
            return { label: "ON", look: "busy", color: YELLOW, status: "sta elaborando" + ro,
                tip: "Claude sta eseguendo una richiesta." };
        }
        if (agent.pending > 0) {
            return { label: "ON", look: "busy", color: YELLOW, status: "sta ricevendo" + ro,
                tip: "Ci sono richieste di Claude in arrivo." };
        }
        return { label: "ON", look: "on", color: GREEN, status: "in attesa" + ro,
            tip: "Claude pu\u00f2 lavorare in After Effects" + (readOnly ? ", ma solo guardando: non modifica il progetto" : "") + "." };
    }

    var OUTCOME_MARK = {
        ok: "\u2713",
        error: "\u2717",
        paused: "rifiutata (pausa)",
        readonly: "rifiutata (sola lettura)"
    };

    function undoneMarks() {
        try {
            if (!$.global.AE_MCP_PANEL_UNDONE) $.global.AE_MCP_PANEL_UNDONE = {};
            return $.global.AE_MCP_PANEL_UNDONE;
        } catch (eMarks) {
            return {};
        }
    }

    function entryKey(entry) {
        return String(entry.t) + "|" + String(entry.label);
    }

    function isUndone(entry) {
        var marks = undoneMarks();
        return marks.hasOwnProperty(entryKey(entry)) && marks[entryKey(entry)] === true;
    }

    /** Newest first, one line each: time, what, outcome, duration. */
    function historyLines(recent, rows) {
        var lines = [];
        for (var i = recent.length - 1; i >= 0 && lines.length < rows; i--) {
            var e = recent[i];
            if (!e || typeof e.t !== "number") continue;
            var what = (typeof e.title === "string") ? e.title : String(e.label);
            var mark = (typeof e.outcome === "string" && OUTCOME_MARK.hasOwnProperty(e.outcome))
                ? OUTCOME_MARK[e.outcome] : String(e.outcome);
            var tail = (e.outcome === "ok" || e.outcome === "error") ? "  " + seconds(e.ms) : "";
            if (isUndone(e)) {
                mark = "annullata";
                tail = "";
            }
            lines.push(clock(e.t).substring(0, 5) + "  " + shorten(what, TITLE_CHARS) + "  " + mark + tail);
        }
        return lines;
    }

    /** The newest change of Claude's that one Undo would revert, or null. */
    function undoTarget(recent) {
        for (var i = recent.length - 1; i >= 0; i--) {
            var e = recent[i];
            if (e && e.undoable === true && !isUndone(e)) return e;
        }
        return null;
    }

    // --- Restore point (mirrors checkpoint.create) ----------------------
    function stampOf(d) {
        return String(d.getFullYear()) + pad2(d.getMonth() + 1) + pad2(d.getDate()) + "-" +
            pad2(d.getHours()) + pad2(d.getMinutes()) + pad2(d.getSeconds());
    }

    function decodedName(file) {
        var name = String(file.name);
        try { name = decodeURI(name); } catch (eDec) { /* keep raw */ }
        return name;
    }

    function checkpointFolder() {
        var file = app.project.file;
        if (!file) return null;
        return new Folder(file.parent.fsName + "/" + CHECKPOINT_SUBDIR);
    }

    /** { ok, message }. Saves the project, then copies its file; never overwrites. */
    function makeCheckpoint() {
        var file = app.project.file;
        if (!file) {
            return { ok: false, message: "Salva prima il progetto: un progetto mai salvato non ha un file da copiare." };
        }
        var name = decodedName(file);
        var dot = name.lastIndexOf(".");
        if (dot <= 0 || name.substring(dot).toLowerCase() !== ".aep") {
            return { ok: false, message: "Il punto di ripristino dal pannello funziona solo con progetti .aep." };
        }
        var stem = name.substring(0, dot);
        try {
            app.project.save();
        } catch (eSave) {
            return { ok: false, message: "Salvataggio non riuscito: il punto di ripristino non \u00e8 stato creato." };
        }
        file = app.project.file;
        var folder = checkpointFolder();
        if (folder === null) return { ok: false, message: "Il progetto non ha pi\u00f9 un file." };
        if (!folder.exists && !folder.create()) {
            return { ok: false, message: "Non riesco a creare la cartella " + CHECKPOINT_SUBDIR + "." };
        }
        var base = stem + "__" + stampOf(new Date()) + "__" + CHECKPOINT_LABEL;
        var dest = null;
        for (var copy = 1; copy <= CHECKPOINT_MAX_COPY; copy++) {
            var candidate = new File(folder.fsName + "/" + base + (copy > 1 ? " (" + copy + ")" : "") + ".aep");
            if (!candidate.exists) {
                dest = candidate;
                break;
            }
        }
        if (dest === null) return { ok: false, message: "Troppi punti di ripristino con lo stesso nome." };
        if (!file.copy(dest.fsName)) return { ok: false, message: "Copia non riuscita." };
        if (dest.length !== file.length) {
            try { dest.remove(); } catch (eRm) { /* leave it */ }
            return { ok: false, message: "Copia incompleta: il punto di ripristino \u00e8 stato scartato." };
        }
        return { ok: true, message: "Ripristino creato: " + decodedName(dest) };
    }

    function historyFolder() {
        try {
            return new Folder(Folder.userData.fsName + "/Parlez/storico");
        } catch (eFolder) {
            return null;
        }
    }

    // --- Look -------------------------------------------------------------
    // "dialog" is honoured by custom drawing but, on AE 26.5, not by a
    // statictext (seen 2026-10-26: the title stayed small); a named family is.
    var FONT_FAMILIES = ["Tahoma", "dialog"];

    function setFont(ctrl, style, size) {
        for (var i = 0; i < FONT_FAMILIES.length; i++) {
            try {
                ctrl.graphics.font = ScriptUI.newFont(FONT_FAMILIES[i], style, size);
                return;
            } catch (eFont) { /* next family */ }
        }
    }

    function setTextColor(ctrl, rgb) {
        try {
            ctrl.graphics.foregroundColor = ctrl.graphics.newPen(ctrl.graphics.PenType.SOLID_COLOR, rgb, 1);
        } catch (eColor) { /* some versions ignore it: default colour */ }
    }

    function setFill(ctrl, rgb) {
        try {
            ctrl.graphics.backgroundColor = ctrl.graphics.newBrush(
                ctrl.graphics.BrushType.SOLID_COLOR,
                [rgb[0], rgb[1], rgb[2], 1]
            );
        } catch (eFill) { /* no fill */ }
    }

    function text(parent, value, size, color) {
        var t = parent.add("statictext", undefined, value);
        t.alignment = ["fill", "center"];
        if (size) setFont(t, "REGULAR", size);
        setTextColor(t, color || TEXT);
        return t;
    }

    function button(parent, label, tip, width) {
        var b = parent.add("button", undefined, label);
        b.helpTip = tip;
        b.alignment = ["fill", "center"];
        if (width > 0) b.preferredSize.width = width;
        return b;
    }

    function row(parent) {
        var g = parent.add("group");
        g.orientation = "row";
        g.alignChildren = ["fill", "center"];
        g.alignment = ["fill", "top"];
        g.spacing = 4;
        return g;
    }

    /** The pictures' folder: install-panel's, else next to this file in the package. */
    function imageFolder() {
        try {
            if (IMAGE_DIR !== null) return new Folder(IMAGE_DIR);
            if ($.fileName) return new Folder(new File($.fileName).parent.fsName + "/panel-images");
        } catch (eDir) { /* no folder */ }
        return null;
    }

    /**
     * { on, off, busy, idle } ScriptUI images, each with its mouse-over and
     * pressed versions, or null when any picture is missing.
     */
    function loadImages(suffix) {
        try {
            var dir = imageFolder();
            if (dir === null || !dir.exists) return null;
            var out = {};
            for (var i = 0; i < LOOKS.length; i++) {
                var base = dir.fsName + "/" + LOOKS[i];
                var normal = new File(base + suffix + ".png");
                var over = new File(base + "-over" + suffix + ".png");
                var down = new File(base + "-down" + suffix + ".png");
                if (!normal.exists || !over.exists || !down.exists) return null;
                // newImage(normal, disabled, pressed, rollover)
                out[LOOKS[i]] = ScriptUI.newImage(normal.fsName, normal.fsName, down.fsName, over.fsName);
            }
            return out;
        } catch (eImages) {
            return null;
        }
    }

    /** firma.png from the pictures' folder, or null (the signature is then text). */
    function signatureImage() {
        try {
            var dir = imageFolder();
            if (dir === null) return null;
            var f = new File(dir.fsName + "/firma.png");
            return f.exists ? ScriptUI.newImage(f.fsName) : null;
        } catch (eSig) {
            return null;
        }
    }

    /** Hand SITE_URL to the operating system, which opens the user's browser. */
    function openSite() {
        try {
            if (String($.os).indexOf("Windows") >= 0) system.callSystem("cmd /c start \"\" \"" + SITE_URL + "\"");
            else system.callSystem("open \"" + SITE_URL + "\"");
        } catch (eOpen) {
            say("Non riesco ad aprire il browser: " + SITE_URL);
        }
    }

    // --- Building (once, when the panel opens) --------------------------
    var isPanel = (typeof Panel !== "undefined") && (thisObj instanceof Panel);
    var win = isPanel ? thisObj : new Window("palette", TITLE, undefined, { resizeable: true });
    var layout = readLayout();
    var compact = (layout === "compatta");
    var notice = "";
    var BUTTON_WIDTH = compact ? 76 : 100;
    // The smallest the panel may get, docked or floating: what its content
    // needs (the ON/OFF picture does not shrink). Without it a floating
    // panel collapsed to the size of its close button (AE 26.5, 2026-10-27).
    var MIN_SIZE = compact ? [760, 210] : [344, 440];
    var BLOCK_SIZE = compact ? [200, 56] : [320, 88];

    var ui = { rows: [], lastLook: "", shown: {}, rowsOpen: true };
    var LOOKS = ["on", "off", "busy", "idle"];

    // Every block of the interface is built inside guard(): an error shows
    // up in the panel itself, with its line, instead of After Effects'
    // "Unable to execute script" that keeps the panel from opening at all.
    var failures = [];
    function guard(name, fn) {
        try {
            fn();
            return true;
        } catch (e) {
            var where = "";
            var what = "errore";
            try { if (e.line !== undefined && e.line !== null) where = " (riga " + String(e.line) + ")"; } catch (eLine) { /* no line */ }
            try { if (e.message) what = String(e.message); } catch (eMsg) { /* no message */ }
            failures.push(name + where + ": " + what);
            return false;
        }
    }

    guard("aspetto", function () {
        setFill(win, BG);
        win.orientation = compact ? "row" : "column";
        win.alignChildren = ["fill", "top"];
        win.spacing = compact ? 12 : 8;
        win.margins = compact ? [10, 8, 10, 8] : 12;
        win.minimumSize = MIN_SIZE;
        win.preferredSize = MIN_SIZE;
    });

    guard("riquadro", function () {
        // The ON/OFF block, status, read-only. No title: the panel's tab already
        // says "Parlez!".
        var head = win.add("group");
        head.orientation = "column";
        head.alignChildren = ["fill", "top"];
        head.spacing = 6;
        // Every top-level group says how big it needs to be: when After Effects
        // undocks the panel it sizes the floating window from what the content
        // asks for, and groups that only say "fill" ask for nothing.
        head.minimumSize = [BLOCK_SIZE[0], BLOCK_SIZE[1] + 52];
        head.preferredSize = [compact ? BLOCK_SIZE[0] + 10 : BLOCK_SIZE[0], BLOCK_SIZE[1] + 52];

        // The block: a picture button (see STABILITY FIRST above).
        var sizeSuffix = compact ? "-small" : "";
        ui.images = loadImages(sizeSuffix);
        if (ui.images !== null) {
            ui.block = head.add("iconbutton", undefined, ui.images.off, { style: "toolbutton" });
            ui.block.alignment = ["center", "top"];
            // Fixed: the picture is never squeezed or stretched.
            ui.block.preferredSize = BLOCK_SIZE;
            ui.block.minimumSize = BLOCK_SIZE;
            ui.block.maximumSize = BLOCK_SIZE;
        } else {
            ui.block = head.add("button", undefined, "OFF");
            ui.block.alignment = ["fill", "top"];
            ui.block.preferredSize = compact ? [140, 50] : [200, 64];
            setFont(ui.block, "BOLD", compact ? 24 : 32);
        }
        ui.block.helpTip = "Accende o spegne Claude in After Effects.";

        ui.status = head.add("statictext", undefined, "");
        ui.status.justify = "center";
        ui.status.alignment = ["fill", "center"];
        setFont(ui.status, "REGULAR", 11);
        setTextColor(ui.status, [0.70, 0.70, 0.70]);
        ui.readOnly = head.add("checkbox", undefined, "Sola lettura");
        ui.readOnly.helpTip = "Claude pu\u00f2 guardare il progetto ma non modificarlo: le richieste che cambierebbero qualcosa vengono rifiutate.";
    });

    guard("storico", function () {
        // History. While it is empty only its first line shows, so the buttons
        // stay in sight in a short panel.
        ui.hist = win.add("group");
        ui.hist.orientation = "column";
        ui.hist.alignChildren = ["fill", "top"];
        ui.hist.spacing = 2;
        ui.hist.margins = [8, 6, 8, 6];
        setFill(ui.hist, SECTION_BG);
        ui.hist.minimumSize = [compact ? 260 : BLOCK_SIZE[0], 48];
        ui.hist.preferredSize = [compact ? 260 : BLOCK_SIZE[0], compact ? 120 : 160];
        var histTitle = text(ui.hist, "Ultime richieste", 11, DIM);
        histTitle.helpTip = "Le richieste pi\u00f9 recenti di Claude in questa sessione: ora, cosa, esito, durata. Lo storico completo \u00e8 nel bottone Storico.";
        var rowCount = compact ? 5 : 8;
        for (var r = 0; r < rowCount; r++) ui.rows.push(text(ui.hist, "", 11));
    });

    guard("bottoni", function () {
        // Buttons: two rows of three, one word each, the same width, as wide as
        // the block. Then the counters on one grey line, and the signature.
        var tail = win.add("group");
        ui.tail = tail;
        tail.orientation = "column";
        tail.alignChildren = ["fill", "top"];
        tail.alignment = ["fill", "top"];
        tail.spacing = 6;
        var ROW_SIZE = [3 * BUTTON_WIDTH + 8, 26];
        tail.minimumSize = [ROW_SIZE[0], 2 * ROW_SIZE[1] + 50];
        tail.preferredSize = [ROW_SIZE[0], 2 * ROW_SIZE[1] + 50];
        var rowA = row(tail);
        rowA.minimumSize = ROW_SIZE;
        ui.undo = button(rowA, "Annulla", "Annulla l'ultima modifica di Claude (Modifica \u203a Annulla, una volta). Chiede conferma.", BUTTON_WIDTH);
        ui.checkpoint = button(rowA, "Ripristino", "Crea un punto di ripristino adesso: salva il progetto e ne fa una copia in " + CHECKPOINT_SUBDIR + ", accanto al progetto.", BUTTON_WIDTH);
        ui.checkpointFolder = button(rowA, "Elenco", "Apre la cartella con l'elenco dei punti di ripristino di questo progetto.", BUTTON_WIDTH);
        var rowB = row(tail);
        rowB.minimumSize = ROW_SIZE;
        ui.history = button(rowB, "Storico", "Apre lo storico completo delle richieste di questa sessione (file di testo).", BUTTON_WIDTH);
        ui.mailbox = button(rowB, "Cassetta", "Apre la cartella dove Claude e After Effects si scambiano le richieste.", BUTTON_WIDTH);
        ui.layout = button(rowB, "Vista", "Passa alla vista " + (compact ? "verticale (colonna laterale)" : "compatta (sotto la timeline)") +
            ". La nuova vista arriva alla prossima apertura del pannello.", BUTTON_WIDTH);
        ui.notice = text(tail, notice, 10, DIM);
        ui.counts = text(tail, "", 9, DIM);
    });

    guard("firma", function () {
        // The signature, glued to the bottom-right corner whatever the panel's
        // size: a group that takes all the space left, with the signature in its
        // bottom-right corner. With firma.png in the pictures' folder it is a
        // toolbutton (see STABILITY FIRST) and a click opens SITE_URL.
        var foot = (compact ? ui.tail : win).add("group");
        foot.orientation = "column";
        foot.alignment = ["fill", "fill"];
        foot.alignChildren = ["right", "bottom"];
        foot.margins = 0;
        foot.minimumSize = [200, 22];
        var signature = signatureImage();
        if (signature !== null) {
            ui.credit = foot.add("iconbutton", undefined, signature, { style: "toolbutton" });
            ui.credit.helpTip = "Another Perspective: apre il sito nel browser.";
        } else {
            // An iconbutton needs a picture: created with null it is a "Bad
            // argument" that stopped the whole panel from opening (AE 26.5,
            // 2026-10-28). Without firma.png the signature is plain text, which
            // After Effects does not let a script make clickable.
            ui.credit = foot.add("statictext", undefined, "Parlez! by Another Perspective");
            ui.credit.justify = "right";
            ui.credit.helpTip = "Another Perspective: " + SITE_URL;
            setFont(ui.credit, "REGULAR", 9);
            setTextColor(ui.credit, DIM);
        }
        ui.credit.alignment = ["right", "bottom"];
    });

    // --- Refreshing: texts and colours only, and only when they change ---
    var current = { agent: null, target: null };

    /**
     * Assign only on change: every assignment can make ScriptUI repaint.
     * `key` names the control and property ("word.text"); nothing is added
     * to the ScriptUI objects themselves.
     */
    function put(key, ctrl, prop, value) {
        // A control whose block failed to build is simply skipped.
        if (!ctrl) return;
        if (ui.shown.hasOwnProperty(key) && ui.shown[key] === value) return;
        ctrl[prop] = value;
        ui.shown[key] = value;
    }

    function say(message) {
        notice = message;
        put("notice.text", ui.notice, "text", message);
    }

    /** The block's picture (or, without pictures, its text), set only when it changes. */
    function paintBlock(state) {
        if (!ui.block || state.look === ui.lastLook) return;
        if (ui.images) ui.block.image = ui.images[state.look];
        else ui.block.text = state.label;
        ui.lastLook = state.look;
    }

    /**
     * Empty history: only the first line, so the box is short. This and
     * opening are the only two moments the panel is laid out again - here at
     * most once per change between "empty" and "not empty".
     */
    function showRows(open) {
        if (open === ui.rowsOpen) return;
        for (var i = 1; i < ui.rows.length; i++) ui.rows[i].visible = open;
        ui.rowsOpen = open;
        if (ui.ready) {
            try { win.layout.layout(true); } catch (eLay) { /* next resize lays it out */ }
        }
    }

    function refresh() {
        var now = new Date().getTime();
        var enabled = readEnabled();
        var readOnly = readReadOnly();
        var agent = readAgent();
        current.agent = agent;

        var state = blockFor(enabled, readOnly, agent, now);
        paintBlock(state);
        put("status.text", ui.status, "text", state.status);
        put("status.helpTip", ui.status, "helpTip", state.tip);

        put("readOnly.value", ui.readOnly, "value", readOnly);
        put("readOnly.enabled", ui.readOnly, "enabled", (agent === null) || (agent.version >= READ_ONLY_AGENT_VERSION));

        var recent = (agent !== null) ? agent.recent : [];
        var lines = historyLines(recent, ui.rows.length);
        showRows(lines.length > 0);
        if (lines.length === 0) lines.push("Nessuna richiesta in questa sessione.");
        for (var i = 0; i < ui.rows.length; i++) put("row" + i, ui.rows[i], "text", (i < lines.length) ? lines[i] : "");

        if (agent === null) {
            put("counts.text", ui.counts, "text", "");
        } else {
            var since = (agent.lastRequestAt > 0)
                ? "ultima " + Math.round((now - agent.lastRequestAt) / 1000) + " s fa"
                : "nessuna richiesta";
            put("counts.text", ui.counts, "text", "eseguite " + agent.served + " \u00b7 rifiutate " + agent.refused + " \u00b7 " + since +
                " \u00b7 " + agent.id + " v" + agent.version);
        }

        current.target = undoTarget(recent);
        put("undo.enabled", ui.undo, "enabled", current.target !== null);
        put("mailbox.enabled", ui.mailbox, "enabled", agent !== null && agent.dir !== null);
        put("checkpointFolder.enabled", ui.checkpointFolder, "enabled", !!app.project.file);
        put("checkpoint.enabled", ui.checkpoint, "enabled", !!app.project.file);
    }

    /**
     * Back to MIN_SIZE when After Effects left the panel collapsed -
     * undocked, it gave the floating window the size of its close button
     * (AE 26.5, 2026-10-27). Only a collapse (under COLLAPSED px), not a
     * narrow column the user docked it in, and at most MAX_FIXES times per
     * opening, so it can never fight the layout from the timer.
     */
    var COLLAPSED = 120;
    var MAX_FIXES = 3;
    var fixes = 0;
    function ensureSize() {
        try {
            if (fixes >= MAX_FIXES) return;
            var sz = win.size;
            if (!sz) return;
            var w = Number(sz[0]);
            var h = Number(sz[1]);
            if (w >= COLLAPSED && h >= COLLAPSED) return;
            fixes++;
            win.size = [Math.max(w, MIN_SIZE[0]), Math.max(h, MIN_SIZE[1])];
            win.layout.layout(true);
            win.layout.resize();
        } catch (eSize) { /* the panel is closing */ }
    }

    /** False while the panel is hidden (a docked tab in the background, a closed window). */
    function isShown() {
        try {
            return win.visible !== false;
        } catch (eVisible) {
            return false;
        }
    }

    // --- Buttons ----------------------------------------------------------
    function toggleClaude() {
        var want = readEnabled() ? "0" : "1";
        say(writeSwitch(KEY_ENABLED, want) ? "" : "Non riesco a salvare la scelta nelle preferenze di After Effects.");
        refresh();
    }
    guard("comandi", function () {
        ui.block.onClick = function () {
            toggleClaude();
            // Nothing stays highlighted after the click.
            try { ui.block.active = false; } catch (eFocus) { /* no focus to drop */ }
        };
        ui.readOnly.onClick = function () {
            if (!writeSwitch(KEY_READ_ONLY, ui.readOnly.value ? "1" : "0")) {
                say("Non riesco a salvare la scelta nelle preferenze di After Effects.");
            }
            ui.shown = {};
            refresh();
        };
        ui.undo.onClick = function () {
            var target = current.target;
            if (target === null) return;
            var what = (typeof target.title === "string") ? target.title : target.label;
            var ok = confirm(
                "Annullo l'ultima modifica di Claude?\n\n" +
                "\u00ab" + what + "\u00bb delle " + clock(target.t) + "\n\n" +
                "After Effects non permette di leggere la cronologia degli annullamenti: " +
                "se dopo hai fatto tu altre modifiche, verr\u00e0 annullata la tua ultima modifica, non quella di Claude."
            );
            if (!ok) return;
            try {
                app.executeCommand(UNDO_COMMAND);
                undoneMarks()[entryKey(target)] = true;
                say("Annullato: " + what + ".");
            } catch (eUndo) {
                say("Annullamento non riuscito.");
            }
            refresh();
        };
        ui.checkpoint.onClick = function () {
            say(makeCheckpoint().message);
            refresh();
        };
        ui.checkpointFolder.onClick = function () {
            var folder = checkpointFolder();
            if (folder === null) say("Il progetto non \u00e8 ancora stato salvato.");
            else if (!folder.exists) say("Nessun punto di ripristino per questo progetto, per ora.");
            else folder.execute();
        };
        ui.history.onClick = function () {
            var agent = current.agent;
            if (agent !== null && agent.historyPath !== null && new File(agent.historyPath).exists) {
                new File(agent.historyPath).execute();
                return;
            }
            var folder = historyFolder();
            if (folder !== null && folder.exists) folder.execute();
            else say("Nessuna richiesta registrata finora.");
        };
        ui.mailbox.onClick = function () {
            var agent = current.agent;
            if (agent === null || agent.dir === null) return;
            var folder = new Folder(agent.dir);
            if (folder.exists) folder.execute();
        };
        // The layout is chosen for the NEXT opening: rebuilding the controls of
        // an open panel is exactly what this build stays away from.
        ui.layout.onClick = function () {
            var next = compact ? "verticale" : "compatta";
            if (writeSwitch(KEY_LAYOUT, next)) say("Vista " + next + ": chiudi e riapri il pannello per vederla.");
        };
    });

    // Safe by default: with no choice saved yet, save "Claude fermo" - the
    // rule already reads "absent" as stopped; saving makes the choice
    // explicit and shows at once whether After Effects keeps it.
    if (readSwitch(KEY_ENABLED) === null && !writeSwitch(KEY_ENABLED, "0")) {
        say("Non riesco a salvare la scelta nelle preferenze di After Effects.");
    }

    // --- The timer ----------------------------------------------------------
    // One per After Effects session: a new opening cancels the previous one's
    // before registering its own. A refresh that throws means the controls
    // are gone - a docked panel that was closed - and stops it for good.
    function stopTimer() {
        try {
            var registered = $.global.AE_MCP_PANEL;
            if (registered && registered.taskId !== null && registered.taskId !== undefined) {
                app.cancelTask(registered.taskId);
                registered.taskId = null;
            }
        } catch (eStop) { /* nothing scheduled */ }
    }

    stopTimer();
    $.global.AE_MCP_PANEL = {
        taskId: null,
        refresh: function () {
            try {
                if (!isShown()) return;
                ensureSize();
                refresh();
            } catch (eRefresh) {
                stopTimer();
            }
        },
        // Once, shortly after opening: by then After Effects has placed the
        // panel (docked or floating) and its real size is known.
        settle: function () {
            ensureSize();
        }
    };

    win.onResizing = win.onResize = function () {
        try {
            this.layout.resize();
        } catch (eResize) {
            try { win.layout.resize(); } catch (eResize2) { /* ignore */ }
        }
    };
    win.onShow = function () {
        ensureSize();
    };
    guard("firma: clic", function () {
        if (ui.credit && ui.credit.type === "iconbutton") {
            ui.credit.onClick = function () {
                openSite();
                try { ui.credit.active = false; } catch (eFocus) { /* no focus to drop */ }
            };
        }
    });

    guard("primo aggiornamento", refresh);
    ui.ready = true;
    if (failures.length > 0) {
        guard("messaggio d'errore", function () {
            var report = win.add("statictext", undefined,
                "Parlez!: una parte del pannello non si \u00e8 aperta. " + failures.join(" \u00b7 "),
                { multiline: true });
            report.alignment = ["fill", "top"];
            report.preferredSize = [MIN_SIZE[0] - 24, 60];
        });
    }
    // After every child is in: lay out, then fit to the current size (the
    // dockable-panel pattern of Adobe's JavaScript Tools Guide and of Peter
    // Kahrel's "ScriptUI for Dummies").
    guard("disposizione", function () {
        win.layout.layout(true);
        win.layout.resize();
    });
    if (!isPanel) {
        win.onClose = function () {
            stopTimer();
        };
        win.center();
        win.show();
    }
    try {
        app.scheduleTask("$.global.AE_MCP_PANEL.settle()", 300, false);
    } catch (eSettle) { /* the timer checks the size too */ }
    try {
        $.global.AE_MCP_PANEL.taskId = app.scheduleTask("$.global.AE_MCP_PANEL.refresh()", REFRESH_MS, true);
    } catch (eSchedule) { /* refreshed by the buttons only */ }
})(this);
